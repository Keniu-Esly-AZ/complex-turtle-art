def posicion(x,y, p, c=str("black")):
    tr.penup()
    tr.goto(x,y)
    tr.pendown()
    tr.pensize(p)
    tr.pencolor(c)

def estampas(x,y,l,w,i,f=str("classic"),b=str("#000000"),c=str("#000000")):
    tr.penup()
    tr.goto(x,y)
    tr.pendown()
    tr.shape(f)
    tr.shapesize(stretch_len= l, stretch_wid= w)
    tr.pencolor(b)
    tr.fillcolor(c)
    tr.tilt(i)
    tr.stamp()

def arbustos(x, y, b, p, a, s, r):
    tr.color("#3A2433","#3A2433")
    tr.pensize(0)
    tr.penup()
    tr.goto(x, y)
    tr.seth(b)
    tr.pendown()
    paso = 360 / p
    tr.begin_fill()
    for i in range(p):
        tr.seth(b + i * paso * s)
        tr.circle(-r, a)
        tr.left(60)
        tr.circle(r, 1)
    tr.end_fill()
    
def degradado(x, y, lg, ct, ep, cl1, cl2):
    tr.colormode(255)
    tr.setheading(0)

    r1, g1, b1 = cl1
    r2, g2, b2 = cl2

    for i in range(ct):
        r = int(r1 + (r2 - r1) * i / (ct - 1))
        g = int(g1 + (g2 - g1) * i / (ct - 1))
        b = int(b1 + (b2 - b1) * i / (ct - 1))

        tr.pencolor(r, g, b)

        tr.penup()
        tr.goto(x, y - i * ep)
        tr.pendown()
        tr.fd(lg)
        
