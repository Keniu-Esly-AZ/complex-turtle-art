def posicion(x,y, p, c=str("black")):
    tr.penup()
    tr.goto(x,y)
    tr.pendown()
    tr.pensize(p)
    tr.pencolor(c)
    
def estampas(x,y,l,w,i,f=str("classic"),b=str("#000000"),c=str("#000000")):
    tr.penup()
    tr.goto(x,y)
    tr.pendown()
    tr.shape(f)
    tr.shapesize(stretch_len= l, stretch_wid= w)
    tr.pencolor(b)
    tr.fillcolor(c)
    tr.tilt(i)
    tr.stamp()

tr.pensize(2)
def ladrillo(x, y, ancho, alto, color="sienna"):
    tr.penup()
    tr.goto(x, y)
    tr.pendown()
    tr.fillcolor(color)
    tr.begin_fill()
    for _ in range(2):
        tr.forward(ancho)
        tr.left(90)
        tr.forward(alto)
        tr.left(90)
    tr.end_fill()

def pared_ladrillos(x, y, f, c, ancho=80, alto=40, cl="sienna", cf="white"):
    tr.bgcolor(cf)
    for fila in range(f):
        offset = ancho / 2 if fila % 2 != 0 else 0
        for col in range(c):
            xpos = x + col * ancho - offset
            ypos = y + fila * alto
            ladrillo(xpos, ypos, ancho, alto, cl)
            
