def posicion(x,y, p, c=str("black")):
    tr.penup()
    tr.goto(x,y)
    tr.pendown()
    tr.pensize(p)
    tr.pencolor(c)
    
def estampas(x,y,l,w,i,f=str("classic"),b=str("#000000"),c=str("#000000")):
    tr.penup()
    tr.goto(x,y)
    tr.pendown()
    tr.shape(f)
    tr.shapesize(stretch_len= l, stretch_wid= w)
    tr.pencolor(b)
    tr.fillcolor(c)
    tr.tilt(i)
    tr.stamp()
    
def puntos_aleatorios(c, x1, x2, y1, y2,t_min=0.5, t_max =2,colores=None):
    tr.penup()
    tr.shape("circle")
    if colores is None:
        colores = ["#5A0C0C","#2637CF", "yellow","#590F5C","#973A15"]
    for _ in range(c):
        x = rd.randint(x1, x2)
        y = rd.randint(y1, y2)
        tr.goto(x, y)
        tamaño = rd.uniform(t_min, t_max)
        tr.shapesize(tamaño)
        tr.color(rd.choice(colores))
        tr.stamp()

