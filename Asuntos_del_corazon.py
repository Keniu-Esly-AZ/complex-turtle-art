def corazon(x, y, tamaño=1, inclinacion=0, color_borde="white", color_relleno="red"):
    tr.penup()
    tr.goto(x, y)
    tr.setheading(inclinacion)
    tr.pendown()
    tr.color(color_borde, color_relleno)
    tr.begin_fill()
    tr.left(140)
    tr.forward(111 * tamaño)
    for _ in range(200):
        tr.right(1)
        tr.forward(1 * tamaño)
    tr.left(120)
    for _ in range(200):
        tr.right(1)
        tr.forward(1 * tamaño)
    tr.forward(111 * tamaño)
    tr.end_fill()
    
corazon(-95, 250, 0.3, 10)


tr.up()
tr.done()