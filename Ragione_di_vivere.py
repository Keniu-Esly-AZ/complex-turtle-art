def posicion(x,y, p, c=str("black")):
    tr.penup()
    tr.goto(x,y)
    tr.pendown()
    tr.pensize(p)
    tr.pencolor(c)
    
def penseth(s, p):
    tr.seth(s)
    tr.pensize(p)
    
def lagrima(x, y, tamaño=1, color="black", angulo=0):
    def transformar(px, py):
        tr.begin_fill()
        px *= tamaño
        py *= tamaño
        rad = math.radians(angulo)
        xr = px * math.cos(rad) - py * math.sin(rad)
        yr = px * math.sin(rad) + py * math.cos(rad)
        return xr + x, yr + y
    x0, y0 = transformar(0, 0)
    tr.penup()
    tr.goto(x0, y0)
    tr.pendown()
    tr.color(color)
    tr.seth(290 + angulo)
    tr.fd(20 * tamaño)
    tr.circle(5 * tamaño, 180)
    tr.goto(x0, y0)
    tr.end_fill()
    

