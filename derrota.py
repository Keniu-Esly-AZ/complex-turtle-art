def arbustos(x, y, b, p, a, s, r):
    tr.begin_fill()
    tr.pensize(1)
    tr.penup()
    tr.goto(x, y)
    tr.seth(b)
    tr.pendown()

    paso = 360 / p

    for i in range(p):
        tr.seth(b + i * paso * s)
        tr.circle(-r, a)
        tr.left(60)
        tr.circle(r, 1)
    tr.end_fill()

