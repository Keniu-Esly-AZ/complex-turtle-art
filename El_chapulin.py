def dibujar_C(x, y, tamaño):
    tr.pensize(4)
    tr.penup()
    tr.goto(x, y)
    tr.setheading(180)
    tr.pendown()
    tr.circle(tamaño, 180)


def dibujar_H(x, y, tamaño):
    tr.pensize(4)
    tr.penup()
    tr.goto(x, y)
    tr.setheading(90)
    tr.pendown()
    tr.forward(tamaño)
    tr.penup()
    tr.goto(x, y + tamaño/2)
    tr.setheading(0)
    tr.pendown()
    tr.forward(tamaño/2)
    tr.penup()
    tr.goto(x + tamaño/2, y)
    tr.setheading(90)
    tr.pendown()
    tr.forward(tamaño)


def posicion(x,y, p, c=str("black")):
    tr.penup()
    tr.goto(x,y)
    tr.pendown()
    tr.pensize(p)
    tr.pencolor(c)
    
def penseth(s, p):
    tr.seth(s)
    tr.pensize(p)
    
def estampas(x,y,l,w,i,f=str("classic"),b=str("#000000"),c=str("#000000")):
    tr.penup()
    tr.goto(x,y)
    tr.pendown()
    tr.shape(f)
    tr.shapesize(stretch_len= l, stretch_wid= w)
    tr.pencolor(b)
    tr.fillcolor(c)
    tr.tilt(i)
    tr.stamp()
    
    
