    tr.goto(x, y)
    tr.seth(d)
    tr.pensize(p)
    tr.color("#2D4232","#485F4D")
    for _ in range(c):
        tamaño_actual = t + rd.randint(-v, v)
        base = tr.position()
        direccion_base = tr.heading()
        tr.pendown()
        tr.begin_fill()
        tr.seth(direccion_base + 90 - i)
        tr.circle(-tamaño_actual, 30)
        tr.rt(130)
        tr.circle(-tamaño_actual, 30)
        tr.penup()
        tr.goto(base)
        tr.pendown()
        tr.end_fill()
        tr.penup()
        tr.seth(direccion_base)
