def posicion(x,y, p, c=str("black")):
    tr.penup()
    tr.goto(x,y)
    tr.pendown()
    tr.pensize(p)
    tr.pencolor(c)
    
def estampas(x,y,l,w,i,f=str("classic"),b=str("#000000"),c=str("#000000")):
    tr.penup()
    tr.goto(x,y)
    tr.pendown()
    tr.shape(f)
    tr.shapesize(stretch_len= l, stretch_wid= w)
    tr.pencolor(b)
    tr.fillcolor(c)
    tr.tilt(i)
    tr.stamp()

def puntos_aleatorios(cantidad, x1, x2, y1, y2,tamaño_min=0.5, tamaño_max=2,colores=None):
    tr.penup()
    tr.shape("circle")
    if colores is None:
        colores = ["#f5eaea", "#fceeee", "#ffffff"]
    for _ in range(cantidad):
        x = rd.randint(x1, x2)
        y = rd.randint(y1, y2)
        tr.goto(x, y)
        tamaño = rd.uniform(tamaño_min, tamaño_max)
        tr.shapesize(tamaño)
        tr.color(rd.choice(colores))
        tr.stamp()

    
