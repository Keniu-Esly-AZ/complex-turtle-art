def transformar(x, y, escala, angulo, tx, ty):
    x *= escala
    y *= escala
    rad = math.radians(angulo)
    xr = x * math.cos(rad) - y * math.sin(rad)
    yr = x * math.sin(rad) + y * math.cos(rad)
    return xr + tx, yr + ty


