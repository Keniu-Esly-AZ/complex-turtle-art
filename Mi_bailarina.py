def figura(x, y, angulo, z):
    tr.penup()
    tr.goto(x, y)
    tr.pendown()
    for i in range(6):
        tr.seth(angulo + 90)
        tr.fd(20)
        tr.color("black","#67b946")
        for _ in range(1):
            tr.begin_fill()
            tr.seth(angulo + 205)
            tr.circle(-14, 100)
            tr.seth(angulo + 25)
            tr.circle(-14, 100)
            tr.seth(angulo + 70)
            tr.circle(-14, 100)
            tr.seth(angulo + z)
            tr.circle(-14, 100)
            tr.end_fill()
            
def posicion(x,y, p, c=str("black")):
    tr.penup()
    tr.goto(x,y)
    tr.pendown()
    tr.pensize(p)
    tr.pencolor(c)
    
def estampas(x,y,l,w,i,f=str("classic"),b=str("#000000"),c=str("#000000")):
    tr.penup()
    tr.goto(x,y)
    tr.pendown()
    tr.shape(f)
    tr.shapesize(stretch_len= l, stretch_wid= w)
    tr.pencolor(b)
    tr.fillcolor(c)
    tr.tilt(i)
    tr.stamp()
    
def corazon(x, y, tamaño=2.5, i=50, cb="black", cr="red"):
    tr.pensize(3)
    tr.penup()
    tr.goto(x, y)
    tr.setheading(i)
    tr.pendown()
    tr.color(cb, cr)
    tr.begin_fill()
    tr.left(140)
    tr.forward(111 * tamaño)
    for _ in range(200):
        tr.right(1)
        tr.forward(1 * tamaño)
    tr.left(120)
    for _ in range(200):
        tr.right(1)
        tr.forward(1 * tamaño)
    tr.forward(111 * tamaño)
    tr.end_fill()
    

